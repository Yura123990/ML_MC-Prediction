import streamlit as st
from prediction import predict

# Налаштування вигляду сторінки
st.set_page_config(page_title="Демографічний прогноз", page_icon="📊", layout="wide")

# Головний заголовок
st.title("📊 Система прогнозування демографічного балансу")
st.markdown("Модель оцінки впливу воєнного стану за допомогою машинного навчання та симуляції Монте-Карло.")

# --- БОКОВА ПАНЕЛЬ (Налаштування) ---
st.sidebar.header("⚙️ Налаштування моделі")

# 1. Завантаження файлу (Pandas вміє читати цей об'єкт напряму)
uploaded_file = st.sidebar.file_uploader("Завантажте датасет (main_dataset.csv)", type=["csv"])

# 2. Повзунок для коефіцієнта Ks (за замовчуванням ставимо твої 0.583)
Ks = st.sidebar.slider(
    "Інтегральний коефіцієнт шоку (Ks)",
    min_value=0.100,
    max_value=1.000,
    value=0.583,
    step=0.001
)

st.sidebar.markdown("""
**Довідка по Ks:**
* **1.000** — Базовий прогноз (без війни)
* **0.583** — Диференційована загроза (19 областей)
* **0.473** — Тотальна загроза (24 області)
""")

# --- ГОЛОВНА ЗОНА (Запуск) ---
st.markdown("### Натисніть кнопку нижче для запуску симуляції")

if st.button("🚀 Згенерувати прогноз", type="primary"):
    if uploaded_file is not None:
        with st.spinner("Моделі ШІ та Монте-Карло проводять розрахунки..."):

            # Виклик твоєї функції
            predict(uploaded_file, Ks)

            st.success("Розрахунок успішно завершено!")
    else:
        st.warning("⚠️ Будь ласка, завантажте CSV-файл датасету в боковій панелі ліворуч.")